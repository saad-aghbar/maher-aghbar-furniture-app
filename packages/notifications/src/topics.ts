import type { Permission } from '@maher/permissions';
import type {
  LocaleCopy,
  NotificationEntityType,
  TopicAudience,
  TopicDefinition,
  TopicGroup,
  TopicUrgency,
} from './types';

function L(en: string, ar: string, he: string): LocaleCopy {
  return { en, ar, he };
}

type Spec = {
  code: string;
  group: TopicGroup;
  audiences: readonly TopicAudience[];
  permission?: Permission | readonly Permission[];
  defaultOn?: boolean;
  urgency?: TopicUrgency;
  entity: NotificationEntityType;
  templateCode: string;
  name: LocaleCopy;
  hint: LocaleCopy;
  pushTitle: LocaleCopy;
  pushBody: LocaleCopy;
};

function topic(spec: Spec): TopicDefinition {
  return {
    ...spec,
    defaultOn: spec.defaultOn ?? true,
    urgency: spec.urgency ?? 'normal',
  };
}

