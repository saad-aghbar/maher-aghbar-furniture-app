const byCode = new Map(TOPICS_LIST.map((row) => [row.code, row]));
const byTemplate = new Map(TOPICS_LIST.map((row) => [row.templateCode, row.code]));

export const TOPICS: readonly TopicDefinition[] = TOPICS_LIST;

export function getTopic(code: string | null | undefined): TopicDefinition | undefined {
  if (!code) return undefined;
  return byCode.get(code);
}

export function topicFromTemplateCode(templateCode: string | null | undefined): TopicDefinition | undefined {
  if (!templateCode) return undefined;
  const code = byTemplate.get(templateCode);
  return code ? byCode.get(code) : undefined;
}

export function topicsForGroup(group: TopicGroup): TopicDefinition[] {
  return TOPICS_LIST.filter((row) => row.group === group);
}

export const TOPIC_CODES = TOPICS_LIST.map((row) => row.code);
