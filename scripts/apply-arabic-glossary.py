def transform_string(s: str, phrases: list[tuple[str, str]]) -> str:
    out = s
    for old, new in phrases:
        if old in out:
            out = out.replace(old, new)
    return out


def walk(node, phrases: list[tuple[str, str]]):
    if isinstance(node, dict):
        return {k: walk(v, phrases) for k, v in node.items()}
    if isinstance(node, list):
        return [walk(v, phrases) for v in node]
    if isinstance(node, str):
        return transform_string(node, phrases)
    return node


def count_diffs(a, b) -> int:
    n = 0

    def rec(x, y):
        nonlocal n
        if isinstance(x, dict) and isinstance(y, dict):
            for k in x:
                rec(x[k], y.get(k))
        elif isinstance(x, str) and isinstance(y, str) and x != y:
            n += 1

    rec(a, b)
    return n


def main() -> None:
    total = 0
    for path in sorted(ROOT.glob("*.json")):
        original = json.loads(path.read_text(encoding="utf-8"))
        phrases = list(SAFE_PHRASES)
        if path.name == "mobile.json":
            phrases = POETIC + phrases
        if path.name in DEALER_CUSTOMER_FILES:
            phrases = DEALER_CUSTOMER_PHRASES + phrases
        updated = walk(original, phrases)
        n = count_diffs(original, updated)
        path.write_text(
            json.dumps(updated, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"{path.name}: {n} values changed")
        total += n
    print(f"TOTAL {total}")


if __name__ == "__main__":
    main()
